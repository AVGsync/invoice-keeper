-- Убирает служебные метки памяти («[Инструменты: …]», «[Данные этого ответа …]»), попавшие в сохранённые ответы ассистента.
UPDATE assistant_turns
SET answer_text = btrim(regexp_replace(answer_text, E'\\s*\\[(Данные этого ответа|Инструменты:)[^\\n]*\\]', '', 'g'))
WHERE answer_text ~ E'\\[(Данные этого ответа|Инструменты:)';
